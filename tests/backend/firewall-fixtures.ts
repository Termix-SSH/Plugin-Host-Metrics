export const ok = (stdout = "", stderr = "") => ({ stdout, stderr, code: 0 });
export type CommandResult = {
  stdout: string;
  stderr: string;
  code: number | null;
};
export type FirewallTools = Record<string, CommandResult | Error>;

/** Simulates installed tools and their SSH results, not the collector itself. */
export function firewallRead(
  command: string,
  tools: FirewallTools,
): CommandResult {
  const discovery = command.match(/command -v ([\w-]+) 2>\/dev\/null$/);
  if (discovery)
    return discovery[1] in tools
      ? ok(`/usr/sbin/${discovery[1]}\n`)
      : { stdout: "", stderr: "", code: 1 };
  const tool = command.match(/LC_ALL=C \/usr\/sbin\/([\w-]+)/)?.[1];
  const key =
    tool === "nft" && command.includes("-j list chain") ? "nft-chain" : tool;
  if (
    tool === "nft" &&
    command.includes("-j list ruleset") &&
    !tools["nft-json"]
  ) {
    const input = tools["nft-chain"];
    return input && !(input instanceof Error) ? input : ok('{"nftables":[]}');
  }
  if (
    tool === "nft" &&
    command.includes("-j list ruleset") &&
    tools["nft-json"]
  ) {
    const output = tools["nft-json"];
    if (output instanceof Error) throw output;
    return output;
  }
  const result = key && tools[key];
  if (!result) throw new Error(`Unexpected SSH command: ${command}`);
  if (result instanceof Error) throw result;
  return result;
}
